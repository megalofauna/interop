#!/usr/bin/env node
/*
 * Colour axis guard.
 *
 * The colour system has exactly two axes, and conflating them is the failure
 * this whole rewrite exists to fix:
 *
 *   ELEVATION  --itx-surface / -above / -above-2 / -below
 *              The neutral SUBSTRATE a component stands on. Backgrounds only.
 *              Moves toward light in both schemes.
 *
 *   CONTRAST   --itx-contrast-1 … -6
 *              Everything drawn ON TOP of that substrate — washes, dividers,
 *              borders, icons, text. Moves away from the current surface, so
 *              its direction flips per scheme.
 *
 * Under the old signed `CURRENT±N` shorthand those two read as one ladder, and
 * they drifted into each other repeatedly: --itx-border said one thing while
 * four separate files independently re-derived --itx-neutral-7 as "the house
 * hairline", and every carbon-borrow round had to invert the polarity by hand.
 * Convention did not hold it. Grep was the only detector, and grep is what
 * missed three global-token stomps.
 *
 * So it is a build error. An elevation token on a mark property fails; a
 * contrast token used as a substrate background fails.
 *
 * This is NOT a restriction on overriding. Consumers may set anything, anywhere;
 * it only governs the CSS this library ships.
 *
 * Usage: node scripts/check-color-axes.mjs [root]
 */
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.argv[2] ?? "projects";

/** Generated by scripts/generate-color-ladder.mjs — it defines the axes. */
const GENERATED = /tokens\/elevation\.css$|protocol\/ladder\.css$|ladder\.css-source\.ts$/;
/** Specs deliberately exercise both axes, including the negative cases. */
const SPECS = /\.spec\.ts$/;

const ELEVATION = /--itx-surface(-above(-2)?|-below)?(?![-a-z0-9])/;

/**
 * Only ranks 4–6 are checked as illegal fills. Low ranks legitimately paint
 * backgrounds — a hover wash, a stripe, a selected tint are all "applied on top
 * of the surface", which is the contrast axis by definition, and filing them
 * under elevation is precisely the conflation this guard exists to stop. Ranks
 * 4–6 are text-level separation and are never a fill.
 */
const CONTRAST_FILL = /--itx-contrast-[4-6](?![0-9])/;

/**
 * Properties that paint a MARK. An elevation token here is the error: a border
 * or a glyph is not a substrate, and reading one means it will not hold its
 * contrast when the layer moves.
 */
const MARK_PROPERTY =
	/^(color|border(-(top|right|bottom|left|inline|block)(-(start|end))?)?-color|border-color|outline-color|fill|stroke|text-decoration-color|caret-color|column-rule-color)$/;

/** Properties that paint a SUBSTRATE. A contrast token here is the error. */
const SUBSTRATE_PROPERTY = /^(background|background-color)$/;

/**
 * Custom-property names carry the same intent as the real property they will
 * eventually feed, so they are checked the same way.
 *
 * Substrate is tested FIRST and wins: `--x-background-color` ends in `-color`
 * but is obviously a fill, and a component reading the current surface for its
 * own background is correct, not a violation.
 *
 * A bare `-color` suffix is deliberately NOT treated as a mark. It is genuinely
 * ambiguous — `--x-fade-color` fades to the substrate — and a guard that cries
 * wolf gets switched off, which costs more than the coverage is worth.
 */
/*
 * Token names carry an optional trailing STATE (`-hover`, `-expanded`,
 * `-current`, …) per the naming pattern in .agent/css-strategy.md, so the
 * suffix has to be stripped before classifying. Without that,
 * `--x-divider-color-expanded` reads as neither, and a real violation walks
 * straight through — which is exactly what happened once.
 */
const STATE_SUFFIX =
	/-(hover|active|focus|focus-visible|disabled|selected|checked|current|expanded|collapsed|pressed|open|closed|stuck|invalid|readonly|visited|completed|dragging)$/;

const SUBSTRATE_TOKEN = /-(background|background-color|bg|surface|fill|fade-color|track|backdrop)$/;
const MARK_TOKEN = /-(border-color|divider-color|rule-color|outline-color|foreground|ink|icon-color|text-color|stroke)$/;

function walk(dir, out = []) {
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const p = join(dir, entry.name);
		if (p.includes("node_modules") || p.includes("/dist/")) continue;
		if (entry.isDirectory()) walk(p, out);
		else if (/\.(css|scss)$/.test(entry.name) && !GENERATED.test(p) && !SPECS.test(p)) out.push(p);
	}
	return out;
}

const findings = [];

for (const file of walk(ROOT)) {
	readFileSync(file, "utf8")
		.split("\n")
		.forEach((line, i) => {
			// Comments describe the model constantly; they are not declarations.
			const code = line.replace(/\/\*.*?\*\//g, "").replace(/^\s*\*.*$/, "");
			const decl = code.match(/^\s*(--[a-z0-9-]+|[a-z-]+)\s*:\s*(.+)$/i);
			if (!decl) return;

			const [, name, value] = decl;
			const isCustom = name.startsWith("--");

			/*
			 * `--x: var(--x)` is a cycle: guaranteed-invalid, and it INHERITS, so it
			 * takes the subtree with it. This codebase has now produced one three
			 * times — twice by hand and once from a codemod that mapped both sides
			 * of a rename — and the last one shipped, surviving only because a later
			 * import happened to re-declare the token. Cheap to detect, so detect it.
			 */
			if (isCustom && new RegExp(`var\\(\\s*${name}\\s*[,)]`).test(value)) {
				findings.push({
					file,
					line: i + 1,
					text: line.trim(),
					why: `${name} references itself — a cycle, which computes to guaranteed-invalid and inherits`,
				});
			}
			const base = isCustom ? name.replace(STATE_SUFFIX, "") : name;
			const wantsSubstrate = isCustom ? SUBSTRATE_TOKEN.test(base) : SUBSTRATE_PROPERTY.test(base);
			const wantsMark = !wantsSubstrate && (isCustom ? MARK_TOKEN.test(base) : MARK_PROPERTY.test(base));

			if (wantsMark && ELEVATION.test(value)) {
				findings.push({
					file,
					line: i + 1,
					text: line.trim(),
					why: `elevation token on a mark (${name}) — a border or glyph is not a substrate, and this will not hold its contrast when the layer moves. Use --itx-contrast-N.`,
				});
			}
			if (wantsSubstrate && CONTRAST_FILL.test(value)) {
				findings.push({
					file,
					line: i + 1,
					text: line.trim(),
					why: `text-level contrast rank as a fill (${name}) — use --itx-surface*, a low rank for a wash, or declare a layer`,
				});
			}
		});
}

if (!findings.length) {
	console.log("✓ colour axes clean — no elevation token on a mark, no contrast token as a substrate");
	process.exit(0);
}

console.error(`✗ ${findings.length} axis violation${findings.length === 1 ? "" : "s"}:\n`);
for (const f of findings) {
	console.error(`  ${f.file}:${f.line}`);
	console.error(`    ${f.text.slice(0, 100)}`);
	console.error(`    ${f.why}\n`);
}
process.exit(1);
