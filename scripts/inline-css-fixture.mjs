/**
 * Inline the two colour CSS files as importable strings.
 *
 * Karma runs in a browser and cannot read the filesystem, so a spec that wants
 * to exercise the REAL stylesheet needs it as a string. That is the only job
 * here. The CSS itself is hand-authored source — this script derives nothing,
 * solves nothing, and has no opinion about colour.
 *
 *   node scripts/inline-css-fixture.mjs           write the fixture
 *   node scripts/inline-css-fixture.mjs --check   fail if it is out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = "projects/interop/src/lib/styles";

const INPUTS = [
	["LADDER_CSS", `${SRC}/themes/protocol/ladder.css`],
	["ENGINE_CSS", `${SRC}/tokens/elevation.css`],
];
const OUT = join(REPO, `${SRC}/tokens/ladder.css-source.ts`);

const body = INPUTS.map(
	([name, path]) =>
		`export const ${name} = ${JSON.stringify(readFileSync(join(REPO, path), "utf8"))};\n`,
).join("\n");

const banner =
	`/*\n` +
	` * The colour stylesheets as strings — GENERATED by\n` +
	` * scripts/inline-css-fixture.mjs. Do not edit by hand; edit the CSS.\n` +
	` *\n` +
	` * Specs run in a browser and cannot read files, so this is how they get at\n` +
	` * the real stylesheet rather than a replica that could drift from it.\n` +
	` */\n\n`;

const next = banner + body;

if (process.argv.includes("--check")) {
	const current = readFileSync(OUT, "utf8");
	if (current !== next) {
		console.error(
			"✗ ladder.css-source.ts is stale — run: node scripts/inline-css-fixture.mjs",
		);
		process.exit(1);
	}
	console.log("✓ colour CSS fixture is up to date");
} else {
	writeFileSync(OUT, next);
	console.log(`✓ wrote ${INPUTS.length} stylesheets to ladder.css-source.ts`);
}
